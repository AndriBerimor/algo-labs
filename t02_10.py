def f(n):
    sum = 0
    for i in range(1, n + 1):   
        sum = sum + i           
    return sum

# Відповідь.
# 1) Цикл виконує n ітерацій, кожна за O(1), тому час виконання f(n) = O(n).
# 2) Функція повертає суму 1 + 2 + ... + n = n(n + 1) / 2.
# 3) Так, функцію можна оптимізувати до O(1), використавши формулу суми арифметичної прогресії:


def f_fast(n):
    return n * (n + 1) // 2


if __name__ == "__main__":
    n = int(input("n = "))
    print("f(n)      =", f(n))
    print("f_fast(n) =", f_fast(n))
